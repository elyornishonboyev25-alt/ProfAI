export type Lang = 'uz' | 'ru' | 'en'
export const LANGS: Lang[] = ['uz', 'ru', 'en']

// Telegram does not share a user's country; the app language is the closest signal.
// Mirrors the website: Uzbek → uz, Russia and CIS languages → ru, everyone else → en.
const RUSSIAN_SPEAKING = new Set(['ru', 'uk', 'be', 'kk', 'ky', 'tg', 'tk', 'az', 'hy'])
export function detectLang(code?: string | null): Lang {
  const base = (code ?? '').toLowerCase().slice(0, 2)
  if (base === 'uz') return 'uz'
  if (RUSSIAN_SPEAKING.has(base)) return 'ru'
  return 'en'
}


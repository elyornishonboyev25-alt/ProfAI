export type OwnerLanguage = 'en' | 'ru' | 'uz'
export function ownerText(text: string, language: OwnerLanguage, params: Record<string, string | number> = {}) {
  const template = language === 'en' ? text : labels[text]?.[language] ?? text
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''))
}

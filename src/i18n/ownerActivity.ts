export function activityText(text: string, language: OwnerLanguage, params: Record<string, string | number> = {}) {
  const template = language === 'en' ? text : labels[text]?.[language] ?? ownerText(text, language)
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''))
}

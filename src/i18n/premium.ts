export type PremiumCopyKey = keyof typeof premiumCopy.en
export type PremiumLanguage = keyof typeof premiumCopy

export function premiumLanguage(value: string): PremiumLanguage {
  const language = value.slice(0, 2)
  return language === 'ru' || language === 'uz' ? language : 'en'
}

export function fillPremium(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match))
}
